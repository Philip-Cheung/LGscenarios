import { readdirSync, readFileSync } from 'node:fs'
import { basename, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { scenarioFileSchema, toStoredContent, type ScenarioFile } from '../src/lib/content'

export const MIGRATIONS_DIR = fileURLToPath(new URL('../supabase/migrations/', import.meta.url))
export const SCENARIOS_DIR = fileURLToPath(new URL('../content/scenarios/', import.meta.url))
export const JSON_SCHEMA_PATH = fileURLToPath(new URL('../content/scenario.schema.json', import.meta.url))

export interface LoadedFile {
  path: string
  raw: unknown
}

/** Reads every `content/scenarios/*.json` file without validating it. */
export function readScenarioFiles(): LoadedFile[] {
  return readdirSync(SCENARIOS_DIR)
    .filter((name) => name.endsWith('.json'))
    .sort()
    .map((name) => {
      const path = join(SCENARIOS_DIR, name)
      return { path, raw: JSON.parse(readFileSync(path, 'utf8')) as unknown }
    })
}

/** Expected file name for a scenario version, e.g. `who-is-god.v1.json`. */
export function scenarioFileName(scenario: Pick<ScenarioFile, 'id' | 'version'>): string {
  return `${scenario.id}.v${scenario.version}.json`
}

export function fileNameProblem(path: string, raw: unknown): string | null {
  const parsed = scenarioFileSchema.safeParse(raw)
  if (!parsed.success) return null
  const expected = scenarioFileName(parsed.data)
  return basename(path) === expected ? null : `${basename(path)} should be named ${expected}`
}

export function scenarioMigrationName(scenario: Pick<ScenarioFile, 'id' | 'version' | 'status'>): string {
  const action = scenario.status === 'published' ? 'publish' : 'draft'
  return `scenario_${scenario.id.replaceAll('-', '_')}_v${scenario.version}_${action}`
}

export function listMigrationFiles(): string[] {
  return readdirSync(MIGRATIONS_DIR).filter((name) => name.endsWith('.sql'))
}

export function hasScenarioMigration(scenario: Pick<ScenarioFile, 'id' | 'version' | 'status'>): boolean {
  const name = scenarioMigrationName(scenario)
  return listMigrationFiles().some((file) => file.endsWith(`_${name}.sql`))
}

function formatTimestamp(date: Date): string {
  const pad = (value: number) => String(value).padStart(2, '0')
  return (
    String(date.getUTCFullYear()) +
    pad(date.getUTCMonth() + 1) +
    pad(date.getUTCDate()) +
    pad(date.getUTCHours()) +
    pad(date.getUTCMinutes()) +
    pad(date.getUTCSeconds())
  )
}

function parseTimestamp(value: string): number {
  const match = /^(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})$/.exec(value)
  if (!match) return 0
  const [, y, mo, d, h, mi, s] = match.map(Number)
  return Date.UTC(y, mo - 1, d, h, mi, s)
}

/** Now, or one second after the newest migration if the clock is behind it. */
export function nextMigrationTimestamp(now = new Date(), existing = listMigrationFiles()): string {
  const latest = existing.reduce((max, name) => Math.max(max, parseTimestamp(name.slice(0, 14))), 0)
  return formatTimestamp(new Date(Math.max(now.getTime(), latest + 1000)))
}

function sqlLiteral(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}

function dollarQuote(value: string): string {
  let tag = 'scenario'
  for (let n = 1; value.includes(`$${tag}$`); n += 1) tag = `scenario${n}`
  return `$${tag}$${value}$${tag}$`
}

/**
 * SQL that stores one validated scenario file. Drafts are inserted hidden and
 * may be replaced while still drafts. Publishing freezes the content, opens it
 * for new pairs, and closes older versions of the same scenario. Re-running a
 * migration is harmless; a mismatch with an already-published row fails.
 */
export function buildScenarioMigrationSql(file: ScenarioFile, sourcePath: string): string {
  const content = toStoredContent(file)
  const json = dollarQuote(JSON.stringify(content, null, 2))
  const id = sqlLiteral(file.id)
  const version = String(file.version)
  const count = String(file.questions.length)
  const publish = file.status === 'published'
  const lines = [
    `-- Generated by scripts/publish-scenario.ts from ${sourcePath}. Do not edit.`,
    `-- ${file.id} v${version}: "${file.title.replaceAll('\n', ' ')}" (${count} questions), ${publish ? 'published' : 'draft'}`,
    ``,
    `insert into public.scenario_registry (scenario_id, version, slug, prompt_count, status, content, active_for_new_sessions)`,
    `values (${id}, ${version}, ${id}, ${count}, 'draft', ${json}::jsonb, false)`,
    `on conflict (scenario_id, version) do update`,
    `  set content = excluded.content, prompt_count = excluded.prompt_count`,
    `  where public.scenario_registry.status = 'draft';`,
  ]
  if (publish) {
    lines.push(
      ``,
      `update public.scenario_registry`,
      `set status = 'published', published_at = clock_timestamp()`,
      `where scenario_id = ${id} and version = ${version} and status = 'draft';`,
    )
  }
  lines.push(
    ``,
    `do $$`,
    `begin`,
    `  if not exists (`,
    `    select 1 from public.scenario_registry`,
    `    where scenario_id = ${id} and version = ${version} and slug = ${id}`,
    `      and status = '${file.status}' and prompt_count = ${count}`,
    `      and content = ${json}::jsonb`,
    `  ) then`,
    `    raise exception 'registry entry ${file.id} v${version} does not match ${sourcePath}';`,
    `  end if;`,
    `end;`,
    `$$;`,
  )
  if (publish) {
    lines.push(
      ``,
      `update public.scenario_registry`,
      `set active_for_new_sessions = false`,
      `where scenario_id = ${id} and version <> ${version};`,
      ``,
      `update public.scenario_registry`,
      `set active_for_new_sessions = true`,
      `where scenario_id = ${id} and version = ${version};`,
    )
  }
  return `${lines.join('\n')}\n`
}
