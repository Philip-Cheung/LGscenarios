import { readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import type { ScenarioContent } from '../src/lib/content'

export const MIGRATIONS_DIR = fileURLToPath(new URL('../supabase/migrations/', import.meta.url))

export function registryMigrationName(scenario: Pick<ScenarioContent, 'scenarioId' | 'version'>, publish: boolean) {
  const suffix = publish ? '_publish' : ''
  return `registry_${scenario.scenarioId.replaceAll('-', '_')}_v${scenario.version}${suffix}`
}

export function migrationTimestamp(date = new Date()): string {
  const pad = (value: number) => String(value).padStart(2, '0')
  return (
    String(date.getUTCFullYear()) +
    pad(date.getUTCMonth() + 1) +
    pad(date.getUTCDate()) +
    pad(date.getUTCHours()) +
    pad(date.getUTCMinutes()) +
    pad(date.getUTCSeconds())
  )
}

function sqlLiteral(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}

/** SQL that inserts (and optionally publishes) one validated scenario version. */
export function buildRegistryMigrationSql(scenario: ScenarioContent, publish: boolean): string {
  const id = sqlLiteral(scenario.scenarioId)
  const slug = sqlLiteral(scenario.slug)
  const version = String(scenario.version)
  const count = String(scenario.prompts.length)
  const lines = [
    `-- Generated by scripts/generate-registry-migration.ts from src/scenarios. Do not edit.`,
    `-- ${scenario.scenarioId} v${version}: "${scenario.title.replaceAll('\n', ' ')}" (${count} prompts)`,
    ``,
    `insert into public.scenario_registry (scenario_id, version, slug, prompt_count, active_for_new_sessions)`,
    `values (${id}, ${version}, ${slug}, ${count}, false)`,
    `on conflict (scenario_id, version) do nothing;`,
    ``,
    `do $$`,
    `begin`,
    `  if not exists (`,
    `    select 1 from public.scenario_registry`,
    `    where scenario_id = ${id} and version = ${version} and slug = ${slug} and prompt_count = ${count}`,
    `  ) then`,
    `    raise exception 'registry entry ${scenario.scenarioId} v${version} does not match its content file';`,
    `  end if;`,
    `end;`,
    `$$;`,
  ]
  if (publish) {
    lines.push(
      ``,
      `update public.scenario_registry`,
      `set active_for_new_sessions = true`,
      `where scenario_id = ${id} and version = ${version};`,
    )
  }
  return `${lines.join('\n')}\n`
}

export function listMigrationFiles(): string[] {
  return readdirSync(MIGRATIONS_DIR).filter((name) => name.endsWith('.sql'))
}

export function hasRegistryMigration(scenario: Pick<ScenarioContent, 'scenarioId' | 'version'>): boolean {
  const base = registryMigrationName(scenario, false)
  return listMigrationFiles().some((name) => name.includes(`_${base}.sql`) || name.includes(`_${base}_publish.sql`))
}
